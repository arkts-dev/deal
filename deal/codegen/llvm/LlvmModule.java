package deal.codegen.llvm;

import deal.semantic.ir.FunctionId;
import deal.semantic.ir.LoweredFunction;
import deal.semantic.ir.ModuleId;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The textual LLVM module assembly of the native backend
 * ({@code llvm-native-codegen-cfg-ssa} C2/C8/C9, {@code LlvmModule}).
 *
 * <p>One project emission produces exactly one module text: the header with
 * the pinned {@code target triple = "x86_64-pc-linux-gnu"} (D4), the record
 * layouts of the emitted module and of the runtime ABI mirror, the
 * declarations of the runtime entries the emitted facts reference, the static
 * data (strings, origins, the closed failure-arm table, the per-unit
 * {@code deal_module} records), the generated functions, the six
 * export-surface definitions of {@code entry.h}, and the debug metadata.</p>
 *
 * <p>The emitted module defines no process entry and no runtime-owned symbol
 * (C2/R9): {@code main}, {@code deal_project_main} and the error accessors
 * belong to the runtime translation units. Every ordering below derives from
 * the project, module, function and op orders of the validated IR, so two
 * emissions of one project are byte-identical (C9).</p>
 */
final class LlvmModule {

    /** The pinned target triple (D4). */
    static final String TARGET_TRIPLE = "x86_64-pc-linux-gnu";

    /** The x86-64 data layout of the pinned target. */
    static final String TARGET_DATALAYOUT =
        "e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-f80:128-n8:16:32:64-S128";

    /** The runtime entries the staged skeleton references, in emission order. */
    private static final List<String> REFERENCED_ENTRIES = List.of(
        "deal_arm_table_install",
        "deal_call_frame_push",
        "deal_call_frame_pop",
        "deal_root_frame_enter",
        "deal_root_frame_leave");

    private final LlvmSession session;

    LlvmModule(LlvmSession session) {
        this.session = session;
    }

    /** The complete deterministic module text. */
    String render() {
        Map<String, String> functions = functions();
        List<String> lines = new ArrayList<>();
        lines.add("; DEAL native project module -- generated by"
            + " deal.codegen.llvm.LlvmSemanticEmitter. DO NOT EDIT.");
        lines.add("; entry module: " + session.project().entryModule().path());
        lines.add("source_filename = \"deal.project\"");
        lines.add("target datalayout = \"" + TARGET_DATALAYOUT + "\"");
        lines.add("target triple = \"" + TARGET_TRIPLE + "\"");
        lines.add("");
        lines.addAll(recordLayouts());
        lines.add("");
        for (String entry : REFERENCED_ENTRIES) {
            lines.add(LlvmRuntimeAbi.llvmDeclarationOf(entry));
        }
        lines.add("");
        lines.addAll(session.data.render());
        lines.add("");
        for (String function : functions.values()) {
            lines.add(function);
        }
        lines.add("");
        lines.addAll(session.debug.render());
        return String.join("\n", lines) + "\n";
    }

    /**
     * The emitted project's record layouts: the module-owned C2 records first
     * (their members exist only here), then the runtime ABI record layouts and
     * the opaque C3 representations the mirror names.
     */
    private List<String> recordLayouts() {
        List<String> layouts = new ArrayList<>();
        layouts.add("%struct.deal_module = type { i8*, i32, i32,"
            + " %struct.deal_export_entry* }");
        layouts.add("%struct.deal_export_entry = type { i8*, i8*, i32, i32,"
            + " i8* }");
        layouts.addAll(LlvmTypeMapper.recordDefinitions());
        return List.copyOf(layouts);
    }

    /**
     * Every generated definition of the module, keyed by its IR name: the
     * per-unit module-initialization functions in project order, every
     * lowered function in id order, then the six export-surface functions
     * (C2) and the byte-equality helper the lookup entry uses.
     */
    private Map<String, String> functions() {
        Map<String, String> functions = new LinkedHashMap<>();
        for (ModuleId module : session.modules()) {
            long index = session.moduleIndex(module);
            functions.put("deal_module_init_" + index,
                new LlvmFunctionEmitter(session, session.unitOf(module))
                    .emitUnitInit(module));
        }
        for (ModuleId module : session.modules()) {
            java.util.List<LoweredFunction> orderedFunctions =
                new ArrayList<>(session.unitOf(module).functions().values());
            orderedFunctions.sort(java.util.Comparator.comparing(
                function -> function.functionId().id()));
            for (LoweredFunction function : orderedFunctions) {
                FunctionId id = function.functionId();
                functions.put("F" + id.id(),
                    new LlvmFunctionEmitter(session, session.unitOf(module))
                        .emitFunction(id));
            }
        }
        LlvmFunctionEmitter entryEmitter = new LlvmFunctionEmitter(session,
            session.unitOf(session.project().entryModule()));
        functions.put("deal_project_start", projectStart());
        functions.put("deal_project_run_main",
            entryEmitter.emitRunMain(session.project().entryModule()));
        functions.put("deal_project_exports",
            entryEmitter.emitExports(session.modules()));
        functions.put("deal_export_lookup", entryEmitter.emitExportLookup());
        functions.put("deal_export_invoke", entryEmitter.emitExportInvoke());
        functions.put("deal_async_export_invoke",
            entryEmitter.emitAsyncExportInvoke());
        functions.put("deal_text_equals", entryEmitter.emitTextEquals());
        return functions;
    }

    /**
     * {@code deal_project_start}: install the closed failure-arm table before
     * any user code (R5), then initialize every unit in project dependency
     * order, propagating the first carried Error unchanged (C2/C4).
     */
    private String projectStart() {
        StringBuilder out = new StringBuilder();
        out.append("define %struct.deal_outcome @deal_project_start() {\n");
        out.append("entry:\n");
        out.append(LlvmIrPrinter.indent(1))
            .append("%installed = call i32 @deal_arm_table_install"
                + "(%struct.deal_arm_table* @deal_project_arm_table)\n");
        List<ModuleId> modules = session.modules();
        for (int index = 0; index < modules.size(); index++) {
            long moduleIndex = session.moduleIndex(modules.get(index));
            out.append(LlvmIrPrinter.indent(1)).append("%init").append(index)
                .append(" = call %struct.deal_outcome @deal_module_init_")
                .append(moduleIndex).append("()\n");
            out.append(LlvmIrPrinter.indent(1)).append("%err").append(index)
                .append(" = extractvalue %struct.deal_outcome %init")
                .append(index).append(", 0\n");
            out.append(LlvmIrPrinter.indent(1)).append("%failed").append(index)
                .append(" = icmp ne i8* %err").append(index).append(", null\n");
            out.append(LlvmIrPrinter.indent(1)).append("br i1 %failed")
                .append(index).append(", label %fail").append(index)
                .append(", label %next").append(index).append('\n');
            out.append("fail").append(index).append(":\n");
            out.append(LlvmIrPrinter.indent(1))
                .append("ret %struct.deal_outcome %init").append(index)
                .append('\n');
            out.append("next").append(index).append(":\n");
        }
        out.append(LlvmIrPrinter.indent(1))
            .append("ret %struct.deal_outcome { i8* null }\n}\n");
        return out.toString();
    }

}
