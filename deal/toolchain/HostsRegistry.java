package deal.toolchain;

import java.util.List;
import java.util.Objects;

/**
 * The generated host registry translation unit
 * ({@code llvm-native-host-abi-and-async} H1/H2,
 * {@code llvm-native-backend-integration} D4).
 *
 * <p>One build owns exactly one generated registry unit at
 * {@code <scratch>/hosts_registry.c}. It defines the two published registry
 * symbols — {@code deal_host_registry} and {@code deal_host_registry_count} —
 * exactly once, in deterministic imported-module order, and it never defines a
 * host unit's own registration record: each entry pairs the raw specifier of
 * one imported host declaration module with the address of the registration
 * symbol the matched supplied unit defines.</p>
 *
 * <p>Two shapes exist and no third one does:</p>
 *
 * <ul>
 *   <li>no supplied unit matching a published host declaration header — the
 *       H2 count-zero sentinel: one entry whose members are {@code NULL}, never
 *       looked up, and a count of zero;</li>
 *   <li>one entry per matched published host declaration header, in the
 *       deterministic order of the headers' publication-relative paths.</li>
 * </ul>
 *
 * <p>The generated unit includes {@code deal/native/deal_rt.h} and every
 * matched declaration header (each of which declares
 * {@code extern const deal_host_module deal_host_module_<stem>;}), and it is
 * compiled with the published-root include path of the pinned flag list.</p>
 */
public final class HostsRegistry {

    /** The registry translation unit's file name inside the build scratch. */
    public static final String UNIT_NAME = "hosts_registry.c";

    /** The registration symbol prefix of one host unit ({@code H2}). */
    public static final String SYMBOL_PREFIX = "deal_host_module_";

    /** The published registry array symbol ({@code H2}). */
    public static final String ARRAY_SYMBOL = "deal_host_registry";

    /** The published registry count symbol ({@code H2}). */
    public static final String COUNT_SYMBOL = "deal_host_registry_count";

    private HostsRegistry() {
        // Static generator only; no instances.
    }

    /**
     * One registry entry: the imported host declaration module's raw specifier
     * (its module-id path), the publication-relative header path that declares
     * it, and the supplied host unit's file stem.
     */
    public record Entry(String specifier, String headerPath, String stem) {
        public Entry {
            Objects.requireNonNull(specifier, "specifier");
            Objects.requireNonNull(headerPath, "headerPath");
            Objects.requireNonNull(stem, "stem");
            if (specifier.isBlank() || headerPath.isBlank() || stem.isBlank()) {
                throw new IllegalArgumentException(
                    "a registry entry names its specifier, header and stem");
            }
            if (!headerPath.endsWith(".h")) {
                throw new IllegalArgumentException(
                    "a host declaration header is a '.h' file, got '"
                        + headerPath + "'");
            }
            if (specifier.contains("\\")) {
                throw new IllegalArgumentException(
                    "a module specifier uses '/' separators, got '"
                        + specifier + "'");
            }
        }

        /** The registration symbol the matched host unit defines. */
        public String symbol() {
            return SYMBOL_PREFIX + stem;
        }
    }

    /**
     * Renders the one registry unit for the supplied entries, in the given
     * order. An empty list renders the H2 count-zero sentinel.
     */
    public static String render(List<Entry> entries) {
        Objects.requireNonNull(entries, "entries");
        StringBuilder unit = new StringBuilder();
        unit.append("/*\n")
            .append(" * hosts_registry.c - the generated host registry unit of one\n")
            .append(" * native build. Generated by deal.toolchain.NativeToolchain;\n")
            .append(" * never published and removed with the build scratch.\n")
            .append(" */\n")
            .append("#include \"deal/native/deal_rt.h\"\n");
        for (Entry entry : entries) {
            unit.append("#include \"").append(entry.headerPath()).append("\"\n");
        }
        unit.append('\n');
        if (entries.isEmpty()) {
            unit.append("const deal_host_registry_entry ")
                .append(ARRAY_SYMBOL)
                .append("[1] = {{NULL, NULL}};\n")
                .append("const size_t ")
                .append(COUNT_SYMBOL)
                .append(" = 0;\n");
            return unit.toString();
        }
        unit.append("const deal_host_registry_entry ")
            .append(ARRAY_SYMBOL)
            .append('[').append(entries.size()).append("] = {\n");
        for (Entry entry : entries) {
            unit.append("  {\"").append(entry.specifier()).append("\", &")
                .append(entry.symbol()).append("},\n");
        }
        unit.append("};\n");
        unit.append("const size_t ").append(COUNT_SYMBOL).append(" = ")
            .append(entries.size()).append(";\n");
        return unit.toString();
    }
}
