package deal.ast;

/** Binary operators used in {@link BinaryExpr}. */
public enum BinaryOp {
    ADD,   // +
    SUB,   // -
    MUL,   // *
    DIV,   // /
    MOD,   // %
    POW,   // **
    EQ,    // ===
    NEQ,   // !==
    LT,    // <
    LTE,   // <=
    GT,    // >
    GTE,   // >=
    AND,   // &&
    OR     // ||
}
